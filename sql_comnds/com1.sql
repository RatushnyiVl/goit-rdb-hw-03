DROP TABLE IF EXISTS hw3_data_clean CASCADE;

CREATE TABLE hw3_data_clean (
    customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    age SMALLINT NOT NULL CHECK(age >= 18),
    job VARCHAR(30),
    marital VARCHAR CHECK (marital IN ('married', 'single', 'divorced')),
    education VARCHAR CHECK (education IN ('tertiary', 'secondary', 'primary', 'unknown')),
    is_default BOOLEAN,
    balance NUMERIC(10, 2),
    housing BOOLEAN,
    loan BOOLEAN,
    contact VARCHAR CHECK (contact IN ('cellular', 'telephone', 'unknown')),
    day SMALLINT CHECK(day >= 1 AND day <= 31),
    month VARCHAR(10),
    full_date DATE GENERATED ALWAYS AS (
        MAKE_DATE(
            2020, 
            CASE LOWER(month)
                WHEN 'jan' THEN 1 WHEN 'feb' THEN 2 WHEN 'mar' THEN 3
                WHEN 'apr' THEN 4 WHEN 'may' THEN 5 WHEN 'jun' THEN 6
                WHEN 'jul' THEN 7 WHEN 'aug' THEN 8 WHEN 'sep' THEN 9
                WHEN 'oct' THEN 10 WHEN 'nov' THEN 11 WHEN 'dec' THEN 12
            END,
            day
        )
    ) STORED,
    duration SMALLINT CHECK(duration >= 0),
    campaign INT CHECK(campaign > 0),
    pdays SMALLINT CHECK(pdays >= -1),
    previous INT CHECK(previous >= 0),
    poutcome VARCHAR CHECK (poutcome IN ('success', 'failure', 'other', 'unknown')),
    y BOOLEAN NOT NULL
    );

